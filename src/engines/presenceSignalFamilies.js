export function compileFamilyRegex(patterns = [], { whole = false } = {}) {
  const parts = (patterns || []).map((p) => String(p || '').trim()).filter(Boolean)
  if (!parts.length) return null
  const body = parts.join('|')
  return whole ? new RegExp(body, 'i') : new RegExp(body, 'i')
}

export function matchSignalFamilies(text = '') {
  const value = String(text || '').trim()
  if (!value) return null

  for (const family of PRESENCE_SIGNAL_FAMILIES) {
    const re = compileFamilyRegex(family.patterns)
    if (!re) continue
    if (re.test(value)) {
      return {
        familyId: family.id,
        layer: family.layer,
        confidence: family.confidence,
        needsModelAssist: family.needsModelAssist === true,
        shortContinue: family.shortContinue === true,
        reason: `family:${family.id}`,
      }
    }
  }
  return null
}
